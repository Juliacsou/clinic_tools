'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),os=require('node:os');
const Module=require('node:module'),annual=require('../src/weekly-ahead');
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'weekly-3csv-'));
const workbook=path.join(dir,'weekly.xls');fs.writeFileSync(workbook,'fake.xls');
fs.mkdirSync(path.join(dir,'weekly-reports'));
fs.writeFileSync(path.join(dir,'weekly-reports','settings.json'),JSON.stringify({workbookPath:workbook}));
const csvFolder=path.join(dir,'csv');fs.mkdirSync(csvFolder);
const files={};
files.weekly=path.join(csvFolder,'weekly.csv');
files.doctors=path.join(csvFolder,'doctors.csv');
files.therapists=path.join(csvFolder,'therapists.csv');
files.wrong=path.join(csvFolder,'wrong.csv');
const csv=(rows)=>'Date,Time,Patient,Doctor,Type,Status\n'+rows.join('\n')+'\n';
fs.writeFileSync(files.weekly,csv(['10/29/2026,10:00 AM,A,VT,Office VT,Confirmed','10/29/2026,11:00 AM,B,VT,Virtual VT,Confirmed','10/29/2026,12:00 PM,C,VT,Virtual Orientation,Confirmed']));
fs.writeFileSync(files.doctors,csv(['10/30/2026,10:00 AM,A,Dr,VDE Doctor-Tech,Confirmed','10/31/2026,11:00 AM,B,Dr,NP 99203,Confirmed','11/01/2026,12:00 PM,C,Dr,Patient Consultation,Confirmed','11/02/2026,12:00 PM,D,Dr,EP 99213,Confirmed']));
fs.writeFileSync(files.therapists,csv(['10/29/2027,10:00 AM,E,VT,Virtual Orientation,Confirmed','10/29/2027,11:00 AM,F,VT,Virtual Orientation,Missed']));
fs.writeFileSync(files.wrong,csv(['10/30/2026,10:00 AM,G,VT,Office VT,Confirmed']));
const excel={inspect:async()=>({exists:true,row:4,latestDate:'2026-10-29',existing:{B:999,M:1},weeks:[]}),requireFile:()=>{},sha256:()=>String(fs.statSync(workbook).size)};
const original=Module._load;
Module._load=function(request,parent){if(request==='./weekly-excel'&&parent?.filename?.endsWith('weekly-backend.js'))return excel;return original.apply(this,arguments)};
let register;try{register=require('../src/weekly-backend');}finally{Module._load=original;}
const handlers=new Map();let chosen=files.weekly;
const ipcMain={handle:(key,handler)=>handlers.set(key,handler)};
register({ipcMain,dialog:{showOpenDialog:async()=>({canceled:false,filePaths:[chosen]})},mainWindow:()=>null,dataDir:()=>dir,queueWrite:f=>f()});
const call=(name,...args)=>handlers.get(name)({},...args);
(async()=>{
 let weekly=await call('weekly:import-csv','weekly','2026-10-29','week-all');
 assert.equal(weekly.rows,3);assert.equal(weekly.slotId,'week-all');
 chosen=files.doctors;
 const dr=await call('weekly:import-csv','ahead','2026-10-29','ahead-doctors');
 assert.equal(dr.counts['Patient Consultation'].valid,1);
 await assert.rejects(()=>call('weekly:import-csv','ahead','2026-10-29','ahead-therapists'),/Wrong export/);
 chosen=files.therapists;
 const vt=await call('weekly:import-csv','ahead','2026-10-29','ahead-therapists');
 assert.equal(vt.dates.max,'2027-10-29');
 chosen=files.wrong;
 await assert.rejects(()=>call('weekly:import-csv','ahead','2026-10-29','ahead-therapists'),/Wrong export/);
 const ahead=annual.addFiles(annual.addFiles(null,[dr]),[vt]);
 const payload={weekEnding:'2026-10-29',sources:{weekly,ahead},overrides:{},manual:{K:4}};
 await call('weekly:save-draft',payload);
 const loaded=(await call('weekly:load-draft','2026-10-29')).draft;
 assert.equal(loaded.sources.ahead.files.length,2);
 assert.equal(loaded.sources.weekly.rows,3);
 const persisted=fs.readFileSync(path.join(dir,'weekly-reports','drafts.json'),'utf8');
 assert(!persisted.includes('10:00 AM')&&!persisted.includes('11:00 AM'),'patient-level details must never persist');
 const preview=await call('weekly:preview-write',loaded);
 assert.deepEqual([preview.updates.B,preview.updates.C,preview.updates.D,preview.updates.E,preview.updates.M,preview.updates.J],[2,1,1,1,2,1]);
 assert.equal(preview.updates.K,4);
 assert.equal(preview.updates.F,undefined);
 // A stored four-week Ahead cannot overwrite annual Excel metrics.
 await call('weekly:save-draft',{weekEnding:'2026-10-29',sources:{weekly,ahead:{fileName:'previous-ahead.csv',rows:1,canceled:0,missed:0,counts:{'NP 99203':{total:1,canceled:0,missed:0,valid:1}}}}});
 const legacy=(await call('weekly:load-draft','2026-10-29')).draft;
 assert.equal(legacy.sources.ahead.periodMode,'legacy');
 const saved=await call('weekly:preview-write',legacy);
 assert.equal(saved.updates.B,undefined);assert.equal(saved.updates.M,2);
 console.log('Three-slot IPC, annual date boundary, privacy, Excel preview, VT Sessions and legacy migration: PASS');
})().catch(err=>{console.error(err);process.exitCode=1}).finally(()=>fs.rmSync(dir,{recursive:true,force:true}));
