'use strict';
const assert=require('node:assert/strict');
const core=require('../src/weekly-core'),slots=require('../src/weekly-slots'),annual=require('../src/weekly-ahead');
const week='2026-10-29',p=core.periods(week);
assert.deepEqual(p,{weekly:{start:'2026-10-26',end:week},ahead:{start:'2026-10-30',end:'2027-10-29'}});
assert.deepEqual(slots.slots.map(s=>s.id),['week-all','ahead-doctors','ahead-therapists']);
const parse=(body,group)=>core.parseCsv('Date,Type,Status\n'+body,p[group]);
const weekly=parse('10/29/2026,Office VT,Confirmed\n10/29/2026,Virtual VT,Confirmed\n10/29/2026,Virtual Orientation,Confirmed\n10/29/2026,Virtual Orientation,Missed\n10/29/2026,EP 99213,Confirmed\n10/29/2026,NP 99203,Confirmed\n','weekly');
assert(slots.verify(weekly,'week-all'));
const computed=core.computeMetrics({weekly});
assert.equal(computed.M.value,2,'VT Sessions counts only Office VT and Virtual VT');
assert.equal(computed.J.value,1,'Virtual Orientation counts as New VT Start, excluding missed');
assert.equal(computed.G.value,1,'EP 99213 must not count for Ocular Motor');
assert.equal(computed.H.value,0,'EP/NP 99213/99203 do not count for Perception Tests');
const doctors=parse('10/30/2026,VDE Doctor-Tech,Confirmed\n11/01/2026,VIP Doctor Only,Confirmed\n11/02/2026,NP 99203,Confirmed\n11/03/2026,Patient Consultation,Confirmed\n11/04/2026,Patient Consultation,Canceled\n11/05/2026,EP 99213,Confirmed\n','ahead');
const therapists=parse('10/30/2026,Virtual Orientation,Confirmed\n10/31/2026,Virtual Orientation,Confirmed\n11/01/2026,Virtual Orientation,Missed\n','ahead');
assert(slots.verify(doctors,'ahead-doctors'));
assert(slots.verify(therapists,'ahead-therapists'));
assert.throws(()=>slots.verify(weekly,'ahead-therapists'),/Wrong export/);
assert.throws(()=>slots.verify(therapists,'ahead-doctors'),/Wrong export/);
const d={...doctors,slotId:'ahead-doctors',fileName:'dr.csv',fileHash:'hash-doctor',importedAt:'2026-10-29T12:00:00Z'};
const t={...therapists,slotId:'ahead-therapists',fileName:'therapists.csv',fileHash:'hash-therapist',importedAt:'2026-10-29T12:00:00Z'};
const one=annual.addFiles(null,[d]);
assert.equal(one.periodMode,'annual');assert.equal(one.files.length,1);
let calc=core.computeMetrics({ahead:one});
assert.equal(calc.B.value,3);assert.equal(calc.C.value,2);assert.equal(calc.D.value,1);
assert.equal(calc.E,undefined,'Therapist Ahead remains blank until its CSV arrives');
const both=annual.addFiles(one,[t]);
calc=core.computeMetrics({ahead:both});
assert.deepEqual([calc.B.value,calc.C.value,calc.D.value,calc.E.value],[3,2,1,2]);
assert.equal(both.rows,9);assert.equal(both.canceled,1);assert.equal(both.missed,1);
assert.throws(()=>annual.addFiles(both,[t]),/already imported|both/);
assert.throws(()=>annual.addFiles(both,[{...t,fileHash:'new-file'}]),/both/);
const replaced=annual.addFiles(both,[{...t,fileHash:'new-file'}],1);
assert.equal(replaced.files.length,2);
assert.equal(core.computeMetrics({ahead:annual.removeFile(replaced,1)}).E,undefined);
assert.throws(()=>parse('10/29/2026,Virtual Orientation,Confirmed\n','ahead'),/outside/);
assert.throws(()=>parse('10/30/2027,Virtual Orientation,Confirmed\n','ahead'),/outside/);
const nextYear=core.periods('2027-02-28');
assert.equal(nextYear.ahead.start,'2027-03-01');assert.equal(nextYear.ahead.end,'2028-02-29');
console.log('Exactly 3 CSV fields, one-year range, imports, status rules, VT Sessions, and split Ahead: PASS');
